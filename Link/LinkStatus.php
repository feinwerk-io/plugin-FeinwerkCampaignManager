namespace Piwik\Plugins\FeinwerkCampaignManager\Link;

/**
 * The status of a saved link, as on the Feinwerk Campaigns platform (decision 6 of 2026-11-23): a draft can change
 * freely; a live link keeps its target and campaign values, so its numbers stay together. Live once marked live, once
 * its start date is reached, or at the latest with its first visit. Ended: live and its end date passed. Days are
 * YYYY-MM-DD in the website's time zone.
 */
final class LinkStatus
{
    public const DRAFT = 'draft';
    public const LIVE = 'live';
    public const ENDED = 'ended';

    /** why a link is live: marked live by hand, its first day of use reached, its first visit counted */
    public const REASON_MANUAL = 'manual';
    public const REASON_START = 'start';
    public const REASON_VISIT = 'visit';
    /** made live in Feinwerk Campaigns (connected mode: the platform's links redirect at once) */
    public const REASON_PLATFORM = 'platform';

    /** days before a link's creation that must be free of visits before a shared campaign row may make it live */
    public const QUIET_DAYS_BEFORE = 30;

    public static function of(?string $liveAt, ?string $startDate, ?string $endDate, string $today): string
    {
        $live = $liveAt !== null || ($startDate !== null && $startDate !== '' && $startDate <= $today);
        if (!$live) {
            return self::DRAFT;
        }
        return $endDate !== null && $endDate !== '' && $endDate < $today ? self::ENDED : self::LIVE;
    }

    public static function isLocked(string $status): bool
    {
        return $status !== self::DRAFT;
    }

    /**
     * Whether visits counted for a draft's report row are this link's first visit. Never when another saved link shares
     * the row. With its own generated link ID always; with a typed link ID or a row of the campaign (and keyword) only
     * when the row had no visit in the QUIET_DAYS_BEFORE days before the link was created: otherwise links that were
     * never saved here use the value too, and every fresh draft of a running campaign would lock at once.
     *
     * @param string $basisType LinkBasis type
     * @param int $sharedWith active saved links counted by the row (this one included)
     * @param int $visitsBefore visits of the row in the quiet days before the creation day
     * @param int $visitsSince visits of the row from the creation day on
     * @param bool $generatedId the link ID was generated by this plugin (unique), not typed
     */
    public static function liveByVisits(string $basisType, int $sharedWith, int $visitsBefore, int $visitsSince, bool $generatedId = false): bool
    {
        if ($visitsSince <= 0 || $sharedWith > 1) {
            return false;
        }
        // a generated link ID is this link's alone; a typed one may have been used before (another link, an unsaved
        // one), so it needs the quiet days like a campaign row
        if ($basisType === LinkBasis::LINK_ID && $generatedId) {
            return true;
        }
        return $visitsBefore === 0;
    }
}
